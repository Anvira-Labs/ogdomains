#!/usr/bin/env python3
"""Regenerate js/catalogue.js from the owner's category spreadsheet.

    python3 tools/build-catalogue.py ../temp/domain_categories.xlsx

Only the domain and its category number leave the spreadsheet. Its risk, flip and
notes columns are the owner's private working notes and this repo is published,
so they are deliberately NOT copied. Rows come out in display order: within each
category, the sheet's "top flip candidate" rows first, then the sheet's own order.
Stdlib only (an .xlsx is a zip of XML).
"""
import re, sys, zipfile
import xml.etree.ElementTree as ET

M = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'

def read_rows(path):
    z = zipfile.ZipFile(path)
    names = z.namelist()
    ss = []
    if 'xl/sharedStrings.xml' in names:
        for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(M + 'si'):
            ss.append(''.join(t.text or '' for t in si.iter(M + 't')))
    sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml')).find(M + 'sheetData')
    out = []
    for r in sheet.findall(M + 'row'):
        cells = {}
        for c in r.findall(M + 'c'):
            col = re.match(r'[A-Z]+', c.get('r')).group()
            v = c.find(M + 'v')
            if c.get('t') == 'inlineStr':
                val = ''.join(t.text or '' for t in c.iter(M + 't'))
            elif v is None:
                val = ''
            elif c.get('t') == 's':
                val = ss[int(v.text)]
            else:
                val = v.text
            cells[col] = val.strip()
        out.append(cells)
    return out

def main(src, dst):
    rows = read_rows(src)
    head, body = rows[0], rows[1:]
    assert head.get('A') == 'Domain' and head.get('C') == 'Category', 'unexpected sheet layout: %r' % head
    items, seen = [], set()
    for n, r in enumerate(body):
        dom = r.get('A', '').lower()
        if not dom:
            continue
        assert dom not in seen, 'duplicate domain ' + dom
        seen.add(dom)
        cat = int(re.match(r'(\d+)\.', r['C']).group(1))
        items.append((cat, 0 if r.get('E', '').lower() == 'yes' else 1, n, dom))
    items.sort()
    lines = ["// GENERATED by tools/build-catalogue.py from the owner's category spreadsheet. Do not edit by hand.",
             "// [domain, category number], already in display order. Categories are defined in categories.js.",
             "export const CATALOGUE = ["]
    for cat, _, _, dom in items:
        lines.append("  ['%s', %d]," % (dom, cat))
    lines.append("];")
    open(dst, 'w').write('\n'.join(lines) + '\n')
    print('wrote %d domains to %s' % (len(items), dst))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '../temp/domain_categories.xlsx',
         sys.argv[2] if len(sys.argv) > 2 else 'js/catalogue.js')
